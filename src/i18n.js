export function makeT(code) {
  const pack = STRINGS[code] || STRINGS.en;
  const dict = { ...STRINGS.en, ...pack };
  const hasPack = TRANSLATED.has(code);
  return {
    code,
    translated: hasPack && code !== 'en',
    t: (key) => dict[key] || STRINGS.en[key] || key,
  };
}

export function languageByCode(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[LANGUAGES.length - 1];
}
