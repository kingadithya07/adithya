/**
 * Safety number: 60 digits, derived from the sorted pair of public keys. Both
 * sides compute the same value, so users can compare it out-of-band.
 */
export async function safetyNumber(jwkA, jwkB) {
  const keyOf = (j) => `${j.kty}|${j.crv}|${j.x}|${j.y}`;
  const [first, second] = [keyOf(jwkA), keyOf(jwkB)].sort();
  const digest = new Uint8Array(
    await subtle.digest('SHA-256', enc.encode(`safety|${first}|${second}`))
  );
  let digits = '';
  for (let i = 0; i < 30; i += 1) {
    digits += String(digest[i] % 10);
  }
  return digits.match(/.{1,5}/g).join(' ');
}

export function newId() {
  return crypto.randomUUID();
}

export function randomSaltB64() {
  return b64(crypto.getRandomValues(new Uint8Array(16)));
}

/**
 * Client-side image downscale + WebP encode, done before encryption so the
 * bytes that leave the device are already small. The server stays a blind
 * store: it cannot transcode what it cannot decrypt.
 */
export async function compressImage(file, { maxDim = 1280, quality = 0.72 } = {}) {
  const bitmap = await createImageBitmap(file);
  const scale = Math.min(1, maxDim / Math.max(bitmap.width, bitmap.height));
  const w = Math.max(1, Math.round(bitmap.width * scale));
  const h = Math.max(1, Math.round(bitmap.height * scale));
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  ctx.drawImage(bitmap, 0, 0, w, h);
  bitmap.close?.();
  const blob = await new Promise((resolve) =>
    canvas.toBlob(resolve, 'image/webp', quality)
  );
  if (!blob) throw new Error('image_encode_failed');
  return { blob, width: w, height: h, bytes: new Uint8Array(await blob.arrayBuffer()), sourceBytes: file.size };
}
