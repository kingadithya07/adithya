/**
 * BharatChat E2EE — real Web Crypto, no hand-rolled primitives.
 *
 *   ECDH(P-256) → HKDF-SHA256 → AES-256-GCM (12-byte random IV per message)
 *
 * Honest scope notes (see docs/ARCHITECTURE.md §Threat model):
 *  • This is static-static ECDH between two long-term device keys. It is real
 *    encryption with authenticated ciphertexts, but it provides NO forward
 *    secrecy and NO post-compromise security — a Signal/PQXDH ratchet is the
 *    production answer and is not implemented here.
 *  • Private keys live in per-tab sessionStorage, not a TEE/StrongBox keystore.
 *    Closing the tab destroys the key, after which old ciphertext is undecryptable
 *    by design (the UI renders it as a locked placeholder).
 */

const subtle = globalThis.crypto.subtle;
const enc = new TextEncoder();

const HKDF_INFO = enc.encode('bharatchat/msg/v1');
const MEDIA_INFO = enc.encode('bharatchat/media/v1');

export const ALG_LABEL = 'ECDH P-256 → HKDF-SHA256 → AES-256-GCM';

function b64(bytes) {
  let s = '';
  const view = new Uint8Array(bytes);
  for (let i = 0; i < view.length; i += 1) s += String.fromCharCode(view[i]);
  return btoa(s);
}

function unb64(str) {
  const bin = atob(str);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i += 1) out[i] = bin.charCodeAt(i);
  return out;
}

export async function generateKeyPair() {
  return subtle.generateKey({ name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveBits']);
}

/** Public half as a JWK — this is the only thing that ever leaves the device. */
export async function exportPublicJwk(keyPair) {
  const jwk = await subtle.exportKey('jwk', keyPair.publicKey);
  return { kty: 'EC', crv: 'P-256', x: jwk.x, y: jwk.y };
}

export async function exportPrivateJwk(keyPair) {
  return subtle.exportKey('jwk', keyPair.privateKey);
}

export async function importKeyPair(privateJwk, publicJwk) {
  const [privateKey, publicKey] = await Promise.all([
    subtle.importKey('jwk', privateJwk, { name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveBits']),
    subtle.importKey('jwk', publicJwk, { name: 'ECDH', namedCurve: 'P-256' }, true, []),
  ]);
  return { privateKey, publicKey };
}

export async function importPublicJwk(jwk) {
  return subtle.importKey('jwk', jwk, { name: 'ECDH', namedCurve: 'P-256' }, true, []);
}

async function deriveAesKey(privateKey, publicKey, salt, info) {
  const sharedBits = await subtle.deriveBits({ name: 'ECDH', public: publicKey }, privateKey, 256);
  const ikm = await subtle.importKey('raw', sharedBits, 'HKDF', false, ['deriveKey']);
  return subtle.deriveKey(
    { name: 'HKDF', hash: 'SHA-256', salt, info },
    ikm,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt']
  );
}

function aad({ from, to, msgId }) {
  return enc.encode(`bharatchat|v1|${from}|${to}|${msgId}`);
}

/** Encrypt a text message for one recipient. Returns a wire envelope. */
export async function encryptText({ plaintext, myPrivateKey, theirPublicKey, from, to, msgId }) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const key = await deriveAesKey(myPrivateKey, theirPublicKey, salt, HKDF_INFO);
  const ct = await subtle.encrypt({ name: 'AES-GCM', iv, additionalData: aad({ from, to, msgId }) }, key, enc.encode(plaintext));
  return { msgId, ct: b64(ct), iv: b64(iv), salt: b64(salt) };
}

export async function decryptText({ envelope, myPrivateKey, theirPublicKey, from, to }) {
  const key = await deriveAesKey(myPrivateKey, theirPublicKey, unb64(envelope.salt), HKDF_INFO);
  const plain = await subtle.decrypt(
    {
      name: 'AES-GCM',
      iv: unb64(envelope.iv),
      additionalData: aad({ from, to, msgId: envelope.id || envelope.msgId }),
    },
    key,
    unb64(envelope.ct)
  );
  return new TextDecoder().decode(plain);
}

/**
 * Media key derivation. The salt is generated by the sender and travels inside
 * the (already encrypted) message envelope, so the server never learns it.
 */
export async function encryptMediaBytes({ bytes, myPrivateKey, theirPublicKey, saltB64 }) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const key = await deriveAesKey(myPrivateKey, theirPublicKey, unb64(saltB64), MEDIA_INFO);
  const ct = await subtle.encrypt({ name: 'AES-GCM', iv, additionalData: enc.encode('bharatchat|media|v1') }, key, bytes);
  return { ciphertext: new Uint8Array(ct), iv: b64(iv) };
}

export async function decryptMediaBytes({ ciphertext, ivB64, myPrivateKey, theirPublicKey, saltB64 }) {
  const key = await deriveAesKey(myPrivateKey, theirPublicKey, unb64(saltB64), MEDIA_INFO);
  const plain = await subtle.decrypt(
    { name: 'AES-GCM', iv: unb64(ivB64), additionalData: enc.encode('bharatchat|media|v1') },
    key,
    ciphertext
  );
  return new Uint8Array(plain);
}

